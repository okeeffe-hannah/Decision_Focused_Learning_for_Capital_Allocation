#!/usr/bin/env python3
"""Step 2 of the pipeline: outer experiment runner.

Loops over saved DGP panels x model families x architectures, calling the
callable training/eval functions in `common/{pto,blackbox,dfl}_model.py`, and
saves ONE standardised timeseries CSV + ONE metrics row per (seed, lambda, T,
model_family, architecture) combo.

See parse_args for all arguments, a few examples:

--seeds 42 
--lambdas 10 
--model-families pto 
--architectures linear
--Ts 500
--initial-train-frac 0.7
--rho-scales 0.03 
--save-audit-artifacts
--overwrite

"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

import configs
from common.decision import DecisionConfig
from common.dgp import FEATURE_COLS
from common.io_utils import (StudyPaths, ProgressTracker, print_grid_summary,
                              upsert_metrics_row, combo_already_done)
from common.model_config import ModelConfig


def decision_config_from_panel_metadata(meta: dict) -> DecisionConfig:
    """Rebuild the exact DecisionConfig the panel was generated with, from its
    own metadata JSON."""
    c = meta["constants"]
    return DecisionConfig(
        LGD=c["LGD"], K1=c["K1"], ell=c["ell"], Y_BAR=c["Y_BAR"],
        lambda_shortfall=c["lambda_shortfall"], M=c["M"], RHO_SCALE=c["RHO_SCALE"],
        APPLY_PD_FLOOR=c["APPLY_PD_FLOOR"], PD_FLOOR=c["PD_FLOOR"],
        PD_Q_CLIP_LOW=c["PD_CLIP_LOW"], PD_Q_CLIP_HIGH=c["PD_CLIP_HIGH"],
        PD_A_CLIP_LOW=1e-6, PD_A_CLIP_HIGH=0.99,
        ALPHA_BOUNDS=(c["alpha_bounds_min"], c["alpha_bounds_max"]),
        ALPHA_OPT_XATOL=c["alpha_opt_xatol"],
    )


def parse_args():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--seeds", type=int, nargs="+", default=None)
    p.add_argument("--lambdas", type=float, nargs="+", default=None)
    p.add_argument("--Ts", "--sample-lengths", dest="Ts", type=int, nargs="+", default=None,
                    help="Override configs.SAMPLE_LENGTHS (raw sample length T; the panel used "
                         "for training/eval has T-1 rows). Must already be generated by "
                         "run_01_generate_panels.py --Ts ...")
    p.add_argument("--rho-scales", dest="rho_scales", type=float, nargs="+", default=None,
                    help="Override configs.RHO_SCALES (asset-correlation scale). Must already be "
                         "generated by run_01_generate_panels.py --rho-scales ...")
    p.add_argument("--model-families", type=str, nargs="+", default=None,
                    choices=list(configs.MODEL_ARCHITECTURES.keys()))
    p.add_argument("--architectures", type=str, nargs="+", default=None,
                    help="Filter to specific architectures (e.g. linear mlp). Applied "
                         "within whichever model families are selected.")
    p.add_argument("--split", type=str, default=configs.SPLIT_NAME)
    p.add_argument("--initial-train-frac", type=float, default=None,
                    help="Override configs.EVAL_SPLIT_CFG's initial_train_frac (fraction of the "
                         "panel used for the FIRST training window before expanding-window test "
                         "evaluation begins).")
    p.add_argument("--refit-every", type=int, default=configs.REFIT_EVERY)
    p.add_argument("--study-root", type=str, default=str(Path(__file__).resolve().parent))
    p.add_argument("--save-audit-artifacts", dest="save_audit_artifacts", action="store_true",
                    default=configs.SAVE_AUDIT_ARTIFACTS,
                    help="Compute and save the extra stability reference-point artifacts for"
                        "'linear' and 'mlp' architectures. Off by default.")
    p.add_argument("--overwrite", action="store_true",
                    help="Re-run combos even if a metrics row for them already exists.")
    p.add_argument("--list", "--dry-run", dest="list_only", action="store_true",
                    help="Print the combo grid and exit without training anything.")
    return p.parse_args()


def build_combos(args):
    seeds = args.seeds or configs.SEEDS
    lambdas = args.lambdas or configs.LAMBDAS
    Ts = args.Ts or configs.SAMPLE_LENGTHS
    rho_scales = args.rho_scales or configs.RHO_SCALES
    families = args.model_families or list(configs.MODEL_ARCHITECTURES.keys())
    combos = []
    for seed in seeds:
        for lam in lambdas:
            for T in Ts:
                for rho in rho_scales:
                    for family in families:
                        archs = configs.MODEL_ARCHITECTURES[family]
                        if args.architectures:
                            archs = [a for a in archs if a in args.architectures]
                        for arch in archs:
                            combos.append({"seed": seed, "lambda_shortfall": lam, "T": T, "rho_scale": rho,
                                           "model_family": family, "architecture": arch})
    return combos


def split_cfg_for(args) -> dict:
    if args.initial_train_frac is not None:
        return {"initial_train_frac": float(args.initial_train_frac)}
    return dict(configs.EVAL_SPLIT_CFG)


_AUDITED_DFL_PANELS = set()  
_BACKEND_IMPORTED = False


def run_one_combo(combo: dict, args, paths: StudyPaths):
    global _BACKEND_IMPORTED
    if not _BACKEND_IMPORTED:
        # Import take 10-30s, print so this doesn't look hung
        print("    [one-time] importing PyTorch and model backends ", flush=True)
        t_import = time.time()
        from common import pto_model, blackbox_model, dfl_model
        print(f"    [one-time] backend import finished ({time.time() - t_import:.0f}s)", flush=True)
        _BACKEND_IMPORTED = True
    else:
        from common import pto_model, blackbox_model, dfl_model

    seed = combo["seed"]
    lam = combo["lambda_shortfall"]
    T = combo["T"]
    rho = combo["rho_scale"]
    family = combo["model_family"]
    arch = combo["architecture"]
    split_name = args.split

    panel_csv = paths.panel_csv(seed, lam, T, rho)
    meta_path = paths.panel_metadata_json(seed, lam, T, rho)
    if not panel_csv.exists() or not meta_path.exists():
        raise FileNotFoundError(
            f"Missing panel for seed={seed} lambda={lam} T={T} rho_scale={rho}: {panel_csv}. "
            f"Run run_01_generate_panels.py first (--seeds {seed} --lambdas {lam} --Ts {T} --rho-scales {rho})."
        )
    with open(meta_path, "r", encoding="utf-8") as f:
        meta = json.load(f)
    dcfg = decision_config_from_panel_metadata(meta)  
    feature_cols = meta.get("feature_cols", FEATURE_COLS)
    model_cfg = ModelConfig(seed=42) # Seed used for linear models - MLP models use ensemble seeds
    split_cfg = split_cfg_for(args)

    run_dir = paths.run_dir(family, arch, seed, lam, T, rho, split_name)
    run_dir.mkdir(parents=True, exist_ok=True)

    if family == "pto":
        df = pto_model.load_simulated_panel(panel_csv, feature_cols, cfg=dcfg)
        # PTO's training loss does not depends on lambda_shortfall so the fitted 
        # PD forecast for this (seed, architecture, T, rho_scale) is cached and 
        # reused across every lambda instead of being retrained. Only the decision 
        # step (score_pto_forecast) is redone per lambda.
        training_cfg = pto_model.training_relevant_config(
            dcfg, refit_every=args.refit_every, mlp_seeds=configs.MLP_ENSEMBLE_SEEDS, model_cfg=model_cfg)
        cache_forecast_csv = paths.pto_forecast_csv(arch, seed, T, rho, split_name)
        cache_meta_json = paths.pto_forecast_meta_json(arch, seed, T, rho, split_name)

        cache_valid = False
        if cache_forecast_csv.exists() and cache_meta_json.exists() and not args.overwrite:
            with open(cache_meta_json, "r", encoding="utf-8") as f:
                cached_cfg = json.load(f)
            cache_valid = cached_cfg == training_cfg

        if cache_valid:
            print(f"    [pto/{arch}] reusing cached PD forecast for seed={seed} T={T} rho_scale={rho} "
                  f"(training doesn't depend on lambda_shortfall) -> {cache_forecast_csv.name}", flush=True)
            forecast_long = pd.read_csv(cache_forecast_csv)
            forecast_long["date"] = pd.to_datetime(forecast_long["date"])
            forecast_long["feature_date"] = pd.to_datetime(forecast_long["feature_date"])
            history = pd.DataFrame()
            hist_cache = paths.pto_forecast_training_history_csv(arch, seed, T, rho, split_name)
            if hist_cache.exists():
                history = pd.read_csv(hist_cache)
            stab_lin = pd.DataFrame()
            stab_mlp = pd.DataFrame()
            if args.save_audit_artifacts and arch == "linear":
                lin_cache = paths.pto_forecast_stability_linear_csv(seed, T, rho, split_name)
                if lin_cache.exists():
                    stab_lin = pd.read_csv(lin_cache)
            if args.save_audit_artifacts and arch == "mlp":
                mlp_cache = paths.pto_forecast_stability_mlp_csv(seed, T, rho, split_name)
                if mlp_cache.exists():
                    stab_mlp = pd.read_csv(mlp_cache)
        else:
            stability_ref = None
            if args.save_audit_artifacts and arch in ("linear", "mlp"):
                stability_ref = df[feature_cols].to_numpy(dtype=float)
            forecast_long, history, stab_lin, stab_mlp = pto_model.run_expanding_window_pto_forecast(
                df, feature_cols, split_name, split_cfg, arch, dcfg, model_cfg,
                refit_every=args.refit_every, mlp_seeds=configs.MLP_ENSEMBLE_SEEDS,
                stability_reference_X=stability_ref)
            cache_forecast_csv.parent.mkdir(parents=True, exist_ok=True)
            forecast_long.to_csv(cache_forecast_csv, index=False)
            with open(cache_meta_json, "w", encoding="utf-8") as f:
                json.dump(training_cfg, f, indent=2)
            if not history.empty:
                history.to_csv(paths.pto_forecast_training_history_csv(arch, seed, T, rho, split_name), index=False)
            if arch == "linear" and not stab_lin.empty:
                stab_lin.to_csv(paths.pto_forecast_stability_linear_csv(seed, T, rho, split_name), index=False)
            if arch == "mlp" and not stab_mlp.empty:
                stab_mlp.to_csv(paths.pto_forecast_stability_mlp_csv(seed, T, rho, split_name), index=False)

        # PD stability is lambda invariante and cached above alongside the forecast;
        # alpha decision is not and depends on lambda_shortfall, so recompute here
        # if audit artifacts are saved.
        if args.save_audit_artifacts:
            stab_lin = pto_model.add_alpha_to_stability(stab_lin, dcfg)
            stab_mlp = pto_model.add_alpha_to_stability(stab_mlp, dcfg)

        pred_long = pto_model.score_pto_forecast(forecast_long, df, dcfg, split_name)
        model_name = arch
        metrics = pto_model.summarise_pto_run(pred_long, model_name)

    elif family == "blackbox":
        df = blackbox_model.load_simulated_panel(panel_csv, feature_cols)
        stability_ref = None
        if args.save_audit_artifacts and arch in ("linear", "mlp"):
            stability_ref = df[feature_cols].to_numpy(dtype=float)
        pred_long, history, stab_lin, stab_mlp = blackbox_model.run_expanding_window_blackbox(
            df, feature_cols, split_name, split_cfg, arch, dcfg, model_cfg,
            refit_every=args.refit_every, mlp_seeds=configs.MLP_ENSEMBLE_SEEDS,
            stability_reference_X=stability_ref)
        model_name = f"blackbox_{arch}"
        metrics = blackbox_model.summarise_blackbox_run(pred_long, model_name)

    elif family == "dfl":
        df = dfl_model.load_simulated_panel(panel_csv, feature_cols, cfg=dcfg)
        audit_key = (seed, lam, T, rho)
        if audit_key not in _AUDITED_DFL_PANELS:
            print(f"[dfl] gradient audit for seed={seed} lambda={lam} T={T} rho_scale={rho} "
                  f"(bisection solver + implicit-function-theorem gradient vs. finite "
                  f"differences - runs once per panel, before any DFL training):", flush=True)
            dfl_model.run_gradient_audit(df, dcfg, verbose=True)
            _AUDITED_DFL_PANELS.add(audit_key)
        stability_ref = None
        if args.save_audit_artifacts and arch in ("linear", "mlp"):
            stability_ref = df[feature_cols].to_numpy(dtype=float)
        pred_long, history, stab_lin, stab_mlp = dfl_model.run_expanding_window_dfl(
            df, feature_cols, split_name, split_cfg, arch, dcfg, model_cfg,
            refit_every=args.refit_every, mlp_seeds=configs.MLP_ENSEMBLE_SEEDS,
            stability_reference_X=stability_ref)
        model_name = f"dfl_{arch}"
        metrics = dfl_model.summarise_dfl_run(pred_long, model_name)

    else:
        raise ValueError(f"Unknown model family '{family}'.")

    # standardised outputs
    pred_long.to_csv(paths.timeseries_csv(family, arch, seed, lam, T, rho, split_name), index=False)
    if not history.empty:
        history.to_csv(paths.training_history_csv(family, arch, seed, lam, T, rho, split_name), index=False)
    if not stab_lin.empty:
        stab_lin.to_csv(paths.stability_linear_csv(family, seed, lam, T, rho, split_name), index=False)
    if not stab_mlp.empty:
        stab_mlp.to_csv(paths.stability_mlp_csv(family, seed, lam, T, rho, split_name), index=False)

    metrics_row = {"model_family": family, "architecture": arch, "seed": seed,
                   "lambda_shortfall": lam, "T": T, "rho_scale": rho, "split": split_name,
                   "model_name": model_name, **metrics}
    with open(paths.metrics_row_json(family, arch, seed, lam, T, rho, split_name), "w", encoding="utf-8") as f:
        json.dump(metrics_row, f, indent=2)
    upsert_metrics_row(paths.master_metrics_csv, metrics_row)

    return metrics_row


def main():
    args = parse_args()
    combos = build_combos(args)
    # Lists all combinations that will be run
    print_grid_summary(combos, grid_name="Experiment grid (step 2: train + evaluate)")
    # Lists which combos will be run without running any experiments
    if args.list_only:
        return
    paths = StudyPaths(study_root=Path(args.study_root))
    paths.ensure_dirs()
    tracker = ProgressTracker(total_units=len(combos), label="combo")
    for combo in combos:
        desc = (f"seed={combo['seed']} lambda={combo['lambda_shortfall']} T={combo['T']} "
                f"rho_scale={combo['rho_scale']} {combo['model_family']}/{combo['architecture']} "
                f"split={args.split}")

        # Checks to see if experiment already complete and overwrite flag not given
        if not args.overwrite and combo_already_done(
                paths.master_metrics_csv, combo["model_family"], combo["architecture"],
                combo["seed"], combo["lambda_shortfall"], combo["T"], combo["rho_scale"], args.split):
            tracker.start_unit(desc)
            print("    already in master_metrics.csv -> skipping (use --overwrite to redo)")
            tracker.finish_unit(desc, skipped=True)
            continue

        tracker.start_unit(desc)
        t0 = time.time()
        try:
            row = run_one_combo(combo, args, paths)
            print(f"    mean_regret={row.get('mean_regret'):.6g}  n={row.get('n')}  "
                  f"({time.time() - t0:.0f}s)")
        except FileNotFoundError as exc:
            print(f"    SKIPPED (missing panel): {exc}")
            tracker.finish_unit(desc, skipped=True)
            continue
        tracker.finish_unit(desc)

    print(f"\nMaster metrics table: {paths.master_metrics_csv}")

if __name__ == "__main__":
    main()